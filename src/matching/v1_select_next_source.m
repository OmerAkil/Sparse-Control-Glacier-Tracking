function [NextPoint,Ranked] = v1_select_next_source(Support)
% v1_select_next_source
%
% Deterministic, transparent source-point selection for progressive
% propagation.
%
% Selection rule, in order:
%   1) smaller distance to the 3rd-nearest trusted control (D3)
%      -> compact 3-control local support;
%   2) smaller dominant normalized IDW weight
%      -> avoid priors controlled almost entirely by one nearby seed;
%   3) smaller maximum angular gap among the 3 nearest controls
%      -> better surrounding geometry;
%   4) smaller D2;
%   5) smaller D1;
%   6) prefer inside the current trusted convex hull;
%   7) larger effective IDW control count;
%   8) lower Point ID only as a deterministic final tie-break.
%
% IMPORTANT:
%   InsideTrustedHull is deliberately NOT the primary criterion.
%   A point can lie inside the global trusted hull while still having poor
%   local support. Progressive propagation is therefore driven primarily
%   by local trusted-control geometry.
%
% No arbitrary weighted composite score is used.

required = { ...
    'Point', ...
    'InsideTrustedHull', ...
    'D1_m','D2_m','D3_m', ...
    'EffectiveIDWN', ...
    'DominantIDWWeight', ...
    'MaxAngularGap3_deg'};

assert(istable(Support) && height(Support)>0, ...
    'Support must be a non-empty table.');

assert(all(ismember(required,Support.Properties.VariableNames)), ...
    'Support table has an unexpected schema.');

Ranked = sortrows( ...
    Support, ...
    {'D3_m', ...
     'DominantIDWWeight', ...
     'MaxAngularGap3_deg', ...
     'D2_m', ...
     'D1_m', ...
     'InsideTrustedHull', ...
     'EffectiveIDWN', ...
     'Point'}, ...
    {'ascend', ...
     'ascend', ...
     'ascend', ...
     'ascend', ...
     'ascend', ...
     'descend', ...
     'descend', ...
     'ascend'});

Ranked.SupportRank = (1:height(Ranked))';

Ranked = movevars( ...
    Ranked,'SupportRank','Before','Point');

NextPoint = Ranked.Point(1);

end
